#!/usr/bin/env bash
# heldout_v2.sh [all|jobs|run|eval|audit|analyze|dryrun] : ONE held-out run of all OpenVINS-based methods with back-end v2
#   (warehouse t2 12 seqs + VIODE 12 seqs, 10 methods = the 8 pre-registered + O-Dyn / O-Cls, 10 offsets, rate 0.5
#   -> 2400 runs; results/backend_v2/heldout/runs/<seq>/<method>/run_XX).
# PREPARED BY THE backend_v2 AGENT, NOT RUN. The coordinator launches it after the author-facing freeze:
#   CONFIRM_HELDOUT=yes results/backend_v2/scripts/heldout_v2.sh all
# Guards (also re-checked per container by run_heldout_v2.sh): CONFIRM_HELDOUT=yes; results/backend_v2/backend_config.md5 present and
#   matching; results/p7/final_config(.addendum).md5 matching; bv2_args.py asserts every v2 / roles md5.
# env: PAR (12 containers of this queue), GLOBAL_MAX (12, all bv2h_* containers), BACKEND_VIODE (v2 = identical rule, default;
#   v1 = keep the frozen VIODE estimator), METHODS (space list, default all 10), SEQSET (both | warehouse | viode).
# Time: ~240 s per run -> ~2400 x 240 s / 12 = ~13 h. Disk: ~3.5-4 GB (M2b: 3.1 GB for 1920 runs).
set -euo pipefail
WS=/home/sasa/workspace/savior_ws
H=$WS/results/backend_v2
D=$H/scripts
S=/tmp/claude-1002/-home-sasa-workspace-savior-ws/c06f990f-0719-4913-a626-9c3ce83cc885/scratchpad/bv2
STEP=${1:-all}
if [[ $STEP == dryrun ]]; then   # no container: write the job list to scratch and resolve every job's settings (bv2_args.py)
  JOBS=$S/jobs_heldout_dryrun.txt; CONFIRM_HELDOUT=no
fi
[[ $STEP == dryrun || ${CONFIRM_HELDOUT:-} == yes ]] || { echo "refusing: held-out run needs CONFIRM_HELDOUT=yes (only after the author-facing freeze)"; exit 3; }
(cd $H && md5sum -c --status backend_config.md5) || { echo "refusing: backend_config.yaml md5 mismatch / no md5 file"; exit 3; }
(cd $WS/results/p7 && md5sum -c --status final_config.md5 && md5sum -c --status final_config_addendum.md5) || { echo "refusing: frozen md5"; exit 3; }
export CONFIRM_HELDOUT BACKEND_VIODE=${BACKEND_VIODE:-v2}
mkdir -p $S/logs $S/home $S/roslog
[[ $STEP == dryrun ]] || mkdir -p $H/heldout/runs $H/heldout/tables
METHODS=${METHODS:-openvins savior_none oracle_moving_ext oracle_class_ext oracle_moving oracle_class_naive yolo_naive sens_fix1 p7_nb savior_edge}
JOBS=${JOBS:-$H/heldout/jobs_heldout.txt}
if [[ $STEP == all || $STEP == jobs || $STEP == dryrun ]]; then
  python3 - "$METHODS" "${SEQSET:-both}" > $JOBS <<'EOF'
import sys, yaml
A = yaml.safe_load(open('/home/sasa/workspace/savior_ws/results/p7/final_config_addendum.yaml'))
ms = sys.argv[1].split(); which = sys.argv[2]
seqs = (A['warehouse_heldout']['sequences'] if which in ('both', 'warehouse') else []) + (A['viode']['sequences'] if which in ('both', 'viode') else [])
# heavy (YOLO) jobs first, two 5-offset halves per method x sequence
order = sorted(ms, key=lambda m: m in ('openvins', 'savior_none', 'oracle_moving', 'oracle_class_naive', 'oracle_moving_ext', 'oracle_class_ext'))
print('# backend_v2 held-out (generated by heldout_v2.sh): seq method offsets start')
for s in seqs:
    for m in order:
        print(f'{s} {m} H1 1')
        print(f'{s} {m} H2 6')
EOF
  # replace the half markers by the dataset offsets (warehouse 0.0..1.8 s, VIODE P5 late-start offsets)
  python3 - $JOBS <<'EOF'
import sys
OFF = {'parking_lot': [5.5, 5.7, 5.9, 6.1, 6.3, 6.5, 6.7, 6.9, 7.1, 7.3], 'city_day': [4.1, 4.3, 4.5, 4.7, 4.9, 5.1, 5.3, 5.5, 5.7, 5.9],
       'city_night': [6.1, 6.3, 6.5, 6.7, 6.9, 7.1, 7.3, 7.5, 7.7, 7.9]}
out = []
for l in open(sys.argv[1]):
    p = l.split()
    if l.startswith('#') or len(p) < 4:
        out.append(l.rstrip('\n')); continue
    env = next((e for e in OFF if p[0].startswith(e)), None)
    o = OFF[env] if env else [round(0.2 * k, 1) for k in range(10)]
    h = o[:5] if p[2] == 'H1' else o[5:]
    out.append(f"{p[0]} {p[1]} {','.join(f'{x:.1f}' for x in h)} {p[3]}")
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
EOF
  echo "jobs: $(grep -vc '^#' $JOBS) -> $JOBS"
fi
if [[ $STEP == dryrun ]]; then
  grep -v '^#' $JOBS | awk '{print $1, $2}' | sort -u | while read -r q m; do
    python3 $D/bv2_args.py $q $m v2 > /dev/null || { echo "ARGS FAIL $q $m"; exit 2; }
  done
  echo "dryrun ok: every job resolves (no container started)"; exit 0
fi
if [[ $STEP == all || $STEP == run ]]; then
  # never more than 12 bv2h_ containers; the queue skips method dirs that already hold all requested runs
  DSN=backend_v2/heldout/runs PREFIX=bv2h_ RUNNER=$D/run_heldout_v2.sh QLOG=queue_heldout.log GLOBAL_MAX=${GLOBAL_MAX:-12} \
    python3 $D/bv2queue.py $JOBS ${PAR:-12}
fi
if [[ $STEP == all || $STEP == eval ]]; then
  ROOT=$H/heldout/runs $D/bpy.sh env ROOT=$H/heldout/runs $D/eval_bv2.sh
fi
if [[ $STEP == all || $STEP == audit ]]; then
  # validity: m2b rule (clean exit, FINAL 0 fallbacks / late masks, n_in_core 0, poses >= same-offset openvins (v2) - 1)
  $D/bpy.sh python3 $WS/results/m2b_heldout/scripts/m2bsync.py $H/heldout/runs
  echo "invalid runs -> $H/heldout/tables/invalid.txt (re-run them with FORCE=1 lines, never drop)"
fi
if [[ $STEP == all || $STEP == analyze ]]; then
  for set in t2 viode; do for met in ate rpe; do $D/bpy.sh python3 $D/bv2analyze.py --set $set --metric $met > /dev/null; done; done
  echo "tables -> $H/tables/{ate,rpe}_{t2,viode}.md"
fi
