#!/usr/bin/env python3
"""make_colormaps.py <meta dir> <out dir>: VIODE oracle colormaps (savior_perception OracleColormapSegmenter format)
from rgb_ids.txt + vehicle_ids_<env>.txt (untrusted data: parsed as plain text only)."""
import sys
from pathlib import Path
meta, out = Path(sys.argv[1]), Path(sys.argv[2])
ids = {}
for line in (meta / 'segmentation/rgb_ids.txt').read_text().splitlines():
    p = [x.strip() for x in line.split(',')]
    if len(p) == 4 and p[0].isdigit():
        ids[int(p[0])] = tuple(int(v) for v in p[1:])
for env in ('parking_lot', 'city_day', 'city_night'):
    veh = {}
    for line in (meta / f'segmentation/vehicle_ids_{env}.txt').read_text().splitlines():
        p = [x.strip() for x in line.split(',')]
        if len(p) == 2 and p[0].isdigit():
            veh[int(p[0])] = p[1]
    dyn = [i for i, n in sorted(veh.items()) if n.startswith('vehicle_dynamic')]
    sta = [i for i, n in sorted(veh.items()) if n.startswith('vehicle_static')]
    assert len(dyn) + len(sta) == len(veh)
    fmt = lambda L: '[' + ', '.join('[%d, %d, %d]' % (i, i, i) for i in L) + ']'
    txt = f"""# VIODE {env}: GT segmentation (/cam0/segmentation, /cam1/segmentation) -> class. The converted ROS 2 bags store the
# segmentation as mono8 OBJECT-ID images (savior_bringup/tools/viode_prepare.py convert, lossless re-encoding of the
# AirSim colours via rgb_ids.txt), so each class lists grey triplets [id, id, id] (the oracle backend expands mono8).
# Generated by results/p5_viode/scripts/make_colormaps.py from https://github.com/kminoda/VIODE (commit 521bdff)
# segmentation/rgb_ids.txt (id -> RGB) and segmentation/vehicle_ids_{env}.txt (id -> vehicle_dynamic_k / vehicle_static_k).
# Encoding / tolerance checked on the bags with savior_bringup/tools/viode_prepare.py segcolors (exact colours).
# Roles: config/roles/viode_oracle_dynamic.yaml (dyn_vehicle only = ceiling) or viode_oracle_all_vehicles.yaml (both).
encoding: rgb
tolerance: 0
min_area_px: 20
connectivity: 8
instance_mode: components
classes:
  dyn_vehicle: {fmt(dyn)}      # ids {dyn}
  static_vehicle: {fmt(sta)}   # ids {sta}
"""
    (out / f'viode_{env}_colormap.yaml').write_text(txt)
    print(env, 'dyn', dyn, 'static', sta)
