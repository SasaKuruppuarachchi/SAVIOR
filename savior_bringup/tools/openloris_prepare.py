#!/usr/bin/env python3
"""OpenLORIS-Scene preparation for SAVIOR (T265 fisheye stereo + T265 IMU only).

Reads the original (compressed) ROS1 bags with `rosbags`. Never runs the dataset's decompress.sh.
License: OpenLORIS-Scene is CC BY-ND 4.0 -> converted data stays local (data/openloris/), only this
script and the configs go into the repository.

Subcommands (run inside the ros2_humble container, `python3 -I ...`):
  calib    --bag X.bag [--out kalibr_imucam_chain.yaml]
           T265 calibration from the bag: intrinsics/distortion from /t265/fisheye{1,2}/camera_info
           (Kannala-Brandt4 = OpenVINS 'equidistant'), extrinsics from /tf_static
           (t265_fisheye1 -> t265_fisheye2, t265_fisheye1 -> t265_imu), printed as an OpenVINS
           kalibr_imucam_chain.yaml (T_imu_cam = R_CtoI, p_CinI).
  gt       --bag X.bag --gt per-sequence/<seq>/groundtruth.txt --out gt/<seq>.txt [--frame imu|base_link]
           OpenLORIS GT = pose of `base_link` in `gt_map` (planar: z = 0, roll = pitch = 0; header
           "frame: base_link" in per-scene files; identical to the /gt topic). OpenVINS estimates the
           T265 IMU, so GT is moved to the IMU frame with the bag's static extrinsic:
              T_map_imu(t) = T_map_base(t) * T_base_fisheye1 * T_fisheye1_imu
           (both from /tf_static of the same bag). With --frame base_link the original is copied.
  convert  --bag X.bag --dst ros2/<seq>     convenience wrapper around bag1_to_ros2.py with the T265
           topics, the gyro+accel merge into /t265/imu (accel interpolated to gyro stamps) and the image
           encoding fix 8UC1 -> mono8 (same bytes; cv_bridge refuses 8UC1 -> mono8).
"""
import argparse
import os
import subprocess
import sys
from pathlib import Path

import numpy as np
from rosbags.rosbag1 import Reader
from rosbags.typesys import Stores, get_typestore, get_types_from_msg

T265_TOPICS = ['/t265/fisheye1/image_raw', '/t265/fisheye2/image_raw', '/t265/fisheye1/camera_info',
               '/t265/fisheye2/camera_info', '/t265/gyro/sample', '/t265/accel/sample', '/tf_static',
               '/gt', '/odom']


def open_bag(path):
    r = Reader(Path(path))
    r.open()
    ts = get_typestore(Stores.ROS1_NOETIC)
    add = {}
    for c in r.connections:
        add.update(get_types_from_msg(c.msgdef.data, c.msgtype))
    ts.register(add)
    return r, ts


def q2R(x, y, z, w):
    n = np.sqrt(x * x + y * y + z * z + w * w)
    x, y, z, w = x / n, y / n, z / n, w / n
    return np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
                     [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
                     [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]])


def R2q(R):
    tr = np.trace(R)
    if tr > 0:
        s = 0.5 / np.sqrt(tr + 1.0)
        w, x, y, z = 0.25 / s, (R[2, 1] - R[1, 2]) * s, (R[0, 2] - R[2, 0]) * s, (R[1, 0] - R[0, 1]) * s
    elif R[0, 0] > R[1, 1] and R[0, 0] > R[2, 2]:
        s = 2.0 * np.sqrt(1.0 + R[0, 0] - R[1, 1] - R[2, 2])
        w, x, y, z = (R[2, 1] - R[1, 2]) / s, 0.25 * s, (R[0, 1] + R[1, 0]) / s, (R[0, 2] + R[2, 0]) / s
    elif R[1, 1] > R[2, 2]:
        s = 2.0 * np.sqrt(1.0 + R[1, 1] - R[0, 0] - R[2, 2])
        w, x, y, z = (R[0, 2] - R[2, 0]) / s, (R[0, 1] + R[1, 0]) / s, 0.25 * s, (R[1, 2] + R[2, 1]) / s
    else:
        s = 2.0 * np.sqrt(1.0 + R[2, 2] - R[0, 0] - R[1, 1])
        w, x, y, z = (R[1, 0] - R[0, 1]) / s, (R[0, 2] + R[2, 0]) / s, (R[1, 2] + R[2, 1]) / s, 0.25 * s
    q = np.array([x, y, z, w])
    return q if q[3] >= 0 else -q


def T_from(t, q):
    T = np.eye(4)
    T[:3, :3] = q2R(*q)
    T[:3, 3] = t
    return T


def read_static(bag):
    r, ts = open_bag(bag)
    tf, info = {}, {}
    conns = [c for c in r.connections if c.topic in ('/tf_static', '/t265/fisheye1/camera_info',
                                                      '/t265/fisheye2/camera_info')]
    for c, _, raw in r.messages(connections=conns):
        m = ts.deserialize_ros1(raw, c.msgtype)
        if c.topic == '/tf_static':
            for tr in m.transforms:
                T = tr.transform
                tf[(tr.header.frame_id, tr.child_frame_id)] = T_from(
                    [T.translation.x, T.translation.y, T.translation.z],
                    [T.rotation.x, T.rotation.y, T.rotation.z, T.rotation.w])
        elif c.topic not in info:
            info[c.topic] = m
    r.close()
    return tf, info


def cmd_calib(a):
    tf, info = read_static(a.bag)
    T_c0_c1 = tf[('t265_fisheye1', 't265_fisheye2')]
    T_c0_i = tf[('t265_fisheye1', 't265_imu')]
    T_i_c0 = np.linalg.inv(T_c0_i)
    T_i_c1 = T_i_c0 @ T_c0_c1
    lines = ['%YAML:1.0', '',
             f'# Generated by savior_bringup/tools/openloris_prepare.py calib from {os.path.basename(a.bag)}',
             '# intrinsics: /t265/fisheye{1,2}/camera_info (Kannala-Brandt4 == equidistant), extrinsics: /tf_static',
             '# (T265 factory calibration as recorded by OpenLORIS).', '']
    for i, (topic, T) in enumerate((('/t265/fisheye1', T_i_c0), ('/t265/fisheye2', T_i_c1))):
        ci = info[topic + '/camera_info']
        K = ci.K
        lines += [f'cam{i}:', '  T_imu_cam: #rotation from camera to IMU R_CtoI, position of camera in IMU p_CinI']
        for r in range(4):
            lines.append('    - [' + ', '.join(f'{v:.12f}' if r < 3 else f'{v:.1f}' for v in T[r]) + ']')
        lines += [f'  cam_overlaps: [{1 - i}]', '  camera_model: pinhole',
                  '  distortion_coeffs: [' + ', '.join(f'{v:.12f}' for v in ci.D[:4]) + ']',
                  '  distortion_model: equidistant',
                  f'  intrinsics: [{K[0]:.9f}, {K[4]:.9f}, {K[2]:.9f}, {K[5]:.9f}] #fu, fv, cu, cv',
                  f'  resolution: [{ci.width}, {ci.height}]', f'  rostopic: {topic}/image_raw',
                  '  timeshift_cam_imu: 0.0', '']
    txt = '\n'.join(lines)
    if a.out:
        Path(a.out).write_text(txt)
    print(txt)
    print('# baseline |t_c0_c1| = %.5f m' % np.linalg.norm(T_c0_c1[:3, 3]))


def cmd_gt(a):
    tf, _ = read_static(a.bag)
    T_b_i = tf[('base_link', 't265_fisheye1')] @ tf[('t265_fisheye1', 't265_imu')]
    d = np.loadtxt(a.gt, comments='#')
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, 'w') as f:
        f.write(f'# timestamp tx ty tz qx qy qz qw  (T_gtmap_{a.frame}; source {a.gt})\n')
        for row in d:
            T = T_from(row[1:4], row[4:8])
            if a.frame == 'imu':
                T = T @ T_b_i
            q = R2q(T[:3, :3])
            f.write(f'{row[0]:.9f} {T[0,3]:.6f} {T[1,3]:.6f} {T[2,3]:.6f} {q[0]:.9f} {q[1]:.9f} {q[2]:.9f} {q[3]:.9f}\n')
    print(f'wrote {len(d)} poses ({a.frame} frame) -> {out}')
    print('T_base_imu =\n', np.array2string(T_b_i, precision=6, suppress_small=True))


def cmd_convert(a):
    here = os.path.dirname(os.path.abspath(__file__))
    cmd = [sys.executable, '-I', os.path.join(here, 'bag1_to_ros2.py'), '--src', a.bag, '--dst', a.dst,
           '--topics', *T265_TOPICS, '--merge-imu', '/t265/gyro/sample', '/t265/accel/sample', '/t265/imu',
           # T265 images are recorded as '8UC1'; cv_bridge (OpenVINS) only converts 'mono8' to MONO8
           '--set-encoding', '/t265/fisheye1/image_raw:mono8', '--set-encoding', '/t265/fisheye2/image_raw:mono8']
    print(' '.join(cmd), flush=True)
    sys.exit(subprocess.call(cmd))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    p = sub.add_parser('calib'); p.add_argument('--bag', required=True); p.add_argument('--out')
    p = sub.add_parser('gt'); p.add_argument('--bag', required=True); p.add_argument('--gt', required=True)
    p.add_argument('--out', required=True); p.add_argument('--frame', choices=['imu', 'base_link'], default='imu')
    p = sub.add_parser('convert'); p.add_argument('--bag', required=True); p.add_argument('--dst', required=True)
    a = ap.parse_args()
    {'calib': cmd_calib, 'gt': cmd_gt, 'convert': cmd_convert}[a.cmd](a)


if __name__ == '__main__':
    main()
