"""Export the COCO segmentation set to the Ultralytics YOLO-seg layout (images symlinked, labels = normalised
polygons, one line per polygon: '<cls> x1 y1 x2 y2 ...', class index = COCO id - 1).

  python3 tools/coco_to_yolo.py [data/warehouse/seg_train] [--min-area 40]
-> <root>/yolo/{images,labels}/{train,val}/ + <root>/yolo/data.yaml
"""
import argparse
import json
import os


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('root', nargs='?', default=os.path.join(os.environ.get('SAVIOR_WS', os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..', '..'))), 'data', 'warehouse', 'seg_train'))
    ap.add_argument('--min-area', type=int, default=40)
    args = ap.parse_args()
    y = os.path.join(args.root, 'yolo')
    names = None
    for split in ('train', 'val'):
        d = json.load(open(os.path.join(args.root, 'annotations', f'instances_{split}.json')))
        names = {c['id']: c['name'] for c in d['categories']}
        os.makedirs(os.path.join(y, 'images', split), exist_ok=True)
        os.makedirs(os.path.join(y, 'labels', split), exist_ok=True)
        by_img = {}
        for a in d['annotations']:
            if a['area'] >= args.min_area:
                by_img.setdefault(a['image_id'], []).append(a)
        for im in d['images']:
            base = os.path.splitext(os.path.basename(im['file_name']))[0]
            dst = os.path.join(y, 'images', split, base + '.jpg')
            if not os.path.lexists(dst):
                os.symlink(os.path.relpath(os.path.join(args.root, 'images', im['file_name']), os.path.dirname(dst)), dst)
            W, H = im['width'], im['height']
            with open(os.path.join(y, 'labels', split, base + '.txt'), 'w') as fh:
                for a in by_img.get(im['id'], []):
                    for poly in a['segmentation']:
                        if len(poly) < 6:
                            continue
                        xy = ' '.join(f'{(poly[i] / W if i % 2 == 0 else poly[i] / H):.5f}' for i in range(len(poly)))
                        fh.write(f'{a["category_id"] - 1} {xy}\n')
        print(f'{split}: {len(d["images"])} images')
    with open(os.path.join(y, 'data.yaml'), 'w') as fh:
        fh.write(f'# SAVIOR-Warehouse segmentation set (YOLO-seg layout, generated by tools/coco_to_yolo.py)\npath: {y}\n'
                 'train: images/train\nval: images/val\nnames:\n' +
                 ''.join(f'  {k - 1}: {v}\n' for k, v in sorted(names.items())))
    print(f'wrote {y}/data.yaml')


if __name__ == '__main__':
    main()
