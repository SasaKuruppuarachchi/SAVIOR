"""Generate the savior_bringup configs for SAVIOR-Warehouse from the rig yaml (single source of truth):

  savior_bringup/config/warehouse/{estimator_config.yaml, kalibr_imucam_chain.yaml, kalibr_imu_chain.yaml,
                                   savior_perception.yaml}
  savior_bringup/config/oracle/warehouse_colormap.yaml          (/cam0/segmentation: class colours)
  savior_bringup/config/oracle/warehouse_colormap_moving.yaml   (/cam0/segmentation_moving: moving_<class>)
  savior_bringup/config/roles/warehouse_oracle_moving.yaml      (every moving_<class> is dynamic)

  python3 tools/export_bringup_configs.py [--rig configs/rig_zed2i_4mm.yaml]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)
from wh.classes import CLASSES  # noqa: E402
from wh.rig import load_rig, write_kalibr  # noqa: E402

BRINGUP = os.path.abspath(os.path.join(HERE, '..', '..', 'savior_bringup'))


def estimator_config(rig):
    """OpenVINS estimator config modelled on config/uhumans2 (same keys / order), warehouse specific values."""
    src = open(os.path.join(BRINGUP, 'config', 'uhumans2', 'estimator_config.yaml')).read()
    c = rig['camera']
    hdr = (f'# SAVIOR - SAVIOR-Warehouse (Isaac Sim 6, ZED 2i-like stereo {c["width"]}x{c["height"]} @ {c["rate_hz"]} Hz, '
           f'b = {c["baseline"]} m, fx = {c["fx"]}; analytic IMU 200 Hz).\n'
           '# Generated by savior_datasets/warehouse/tools/export_bringup_configs.py from the uHumans2 config; every\n'
           '# change w.r.t. ref/open_vins/config/euroc_mav is tagged "SAVIOR (...)".')
    src = re.sub(r'^# SAVIOR - uHumans2.*\n# Based on .*\n', hdr + '\n', src, flags=re.M)
    rep = {
        r'^calib_cam_extrinsics: .*$': 'calib_cam_extrinsics: false # SAVIOR (euroc true -> false - simulator extrinsics are exact) # if the transform between camera and IMU should be optimized R_ItoC, p_CinI',
        r'^calib_cam_intrinsics: .*$': 'calib_cam_intrinsics: false # SAVIOR (euroc true -> false - exact rectified pinhole) # if camera intrinsics should be optimized (focal, center, distortion)',
        r'^calib_cam_timeoffset: .*$': 'calib_cam_timeoffset: false # SAVIOR (euroc true -> false - camera and IMU share the simulator clock) # if timeoffset between camera and IMU should be optimized',
        r'^init_imu_thresh: .*$': 'init_imu_thresh: 0.30 # SAVIOR (euroc 1.5 -> 0.30 - drone hovers 3 s then takes off: 0.3 m climb + 1 s ramp to 1 m/s gives an accel std ~0.7; hover std 0.04) # threshold for variance of the accelerometer to detect a "jerk" in motion',
        r'^init_dyn_use: .*$': 'init_dyn_use: true # SAVIOR (false -> true - fallback if the static init is rejected, e.g. by dynamic objects moving during the hover) # if dynamic initialization should be used',
        r'^track_frequency: .*$': f'track_frequency: {float(c["rate_hz"]) + 1.0} # SAVIOR (camera {c["rate_hz"]} Hz) frequency we will perform feature tracking at (in frames per second / hertz)',
    }
    for k, v in rep.items():
        src, n = re.subn(k, v, src, flags=re.M)
        assert n == 1, k
    return src


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rig', default=os.path.join(HERE, 'configs', 'rig_zed2i_4mm.yaml'))
    args = ap.parse_args()
    rig = load_rig(args.rig)
    out = os.path.join(BRINGUP, 'config', 'warehouse')
    os.makedirs(out, exist_ok=True)
    write_kalibr(rig, out)
    with open(os.path.join(out, 'estimator_config.yaml'), 'w') as fh:
        fh.write(estimator_config(rig))
    with open(os.path.join(out, 'savior_perception.yaml'), 'w') as fh:
        fh.write('# SPDX-License-Identifier: GPL-3.0-or-later\n'
                 '# savior_node overrides for SAVIOR-Warehouse (Isaac Sim). Loaded AFTER savior_perception/config/default.yaml\n'
                 '# by savior.launch.py; calib_file / roles_file / colormap_file are set by the launch (absolute share paths).\n'
                 '# Generated by savior_datasets/warehouse/tools/export_bringup_configs.py.\n'
                 'savior_node:\n  ros__parameters:\n    left_topic: /cam0/image_raw\n    right_topic: /cam1/image_raw\n'
                 '    cam_left: cam0\n    cam_right: cam1\n'
                 '    # oracle: GT class-colour image (rgb8, same stamp as the stereo pair); /cam0/segmentation_moving +\n'
                 '    # oracle/warehouse_colormap_moving.yaml + roles/warehouse_oracle_moving.yaml = perfect moving-object masks\n'
                 '    seg_topic: /cam0/segmentation\n    segmenter:\n      backend: oracle_colormap\n'
                 f'    depth:\n      downsample: 2                  # b = {rig["camera"]["baseline"]} m, f = {rig["camera"]["fx"]} px\n')
    ora = os.path.join(BRINGUP, 'config', 'oracle')
    for moving in (False, True):
        name = 'warehouse_colormap_moving.yaml' if moving else 'warehouse_colormap.yaml'
        topic = '/cam0/segmentation_moving' if moving else '/cam0/segmentation'
        lines = [f'# SAVIOR-Warehouse ground-truth colours ({topic}, rgb8) -> class name. Generated by',
                 '# savior_datasets/warehouse/tools/export_bringup_configs.py from wh/classes.py (exact colours, no blending:',
                 '# the image is rendered from the uint16 instance-id GT with a lookup table -> tolerance 0).',
                 '# Format: savior_perception OracleColormapSegmenter (segmenter.backend: oracle_colormap).',
                 '# One colour per CLASS (instance ids are in the raw seg0/ pngs and on /cam0/instance_id); touching instances of',
                 '# one class merge into one component, as with uHumans2.']
        if moving:
            lines += ['# MOVING variant: only instances whose true speed is > 0.05 m/s in that frame are coloured; class names are',
                      '# prefixed with "moving_" so that roles/warehouse_oracle_moving.yaml can make all of them dynamic (oracle',
                      '# "perfect motion masks" upper bound). Static people / parked forklifts are background here.']
        lines += ['encoding: rgb', 'tolerance: 0', 'min_area_px: 30', 'connectivity: 8', 'instance_mode: components', 'classes:']
        for n, role, cid, col in CLASSES:
            lines.append(f'  {("moving_" if moving else "") + n + ":":20s}[[{col[0]}, {col[1]}, {col[2]}]]   # role {role}')
        lines.append('label_ids: {' + ', '.join(f'{("moving_" if moving else "") + n}: {cid}' for n, _, cid, _ in CLASSES) + '}')
        with open(os.path.join(ora, name), 'w') as fh:
            fh.write('\n'.join(lines) + '\n')
    with open(os.path.join(BRINGUP, 'config', 'roles', 'warehouse_oracle_moving.yaml'), 'w') as fh:
        fh.write('# SPDX-License-Identifier: GPL-3.0-or-later\n'
                 '# SAVIOR-Warehouse oracle MOVING masks (/cam0/segmentation_moving + oracle/warehouse_colormap_moving.yaml):\n'
                 '# every coloured instance is truly moving in that frame -> all dynamic (upper bound of motion masking).\n'
                 'dynamic:   [' + ', '.join('moving_' + c[0] for c in CLASSES) + ']\npotential: []\nstatic:    []\n'
                 'default: ignore\n')
    print(f'wrote {out}/, {ora}/warehouse_colormap*.yaml, roles/warehouse_oracle_moving.yaml')


if __name__ == '__main__':
    main()
