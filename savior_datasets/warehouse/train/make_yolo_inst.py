"""Instance-consistent YOLO-seg export of the SAVIOR-Warehouse segmentation set.

tools/coco_to_yolo.py writes ONE LINE PER POLYGON, so an instance that is split by occlusion (68 % of the racks,
55 % of the forklifts, 25 % of the people in train) becomes several separate YOLO instances. Here every COCO
annotation stays ONE instance: its polygons are joined with zero-width bridges (ultralytics
`merge_multi_segment`, the same scheme Ultralytics uses for its own COCO-seg labels). This matches the per-instance
GT of the VIO sequences (seg0/ + instances.json) and what savior_perception consumes (one mask per object).

  python3 make_yolo_inst.py [--root data/warehouse/seg_train] [--out <root>/yolo_inst] [--check 60]

-> <out>/{images,labels}/{train,val}/ (images symlinked) + <out>/data.yaml.
`--check N` rasterises the merged polygons of N val images exactly like the Ultralytics loader (cv2.fillPoly) and
reports the mask IoU against the uint16 GT instance masks (masks/<split>/*.png).
"""
import argparse
import json
import os

import cv2
import numpy as np

WS = os.environ.get('SAVIOR_WS', os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..', '..')))   # colcon workspace (<ws>/src/savior/...)


def merged_polygon(segs):
    from ultralytics.data.converter import merge_multi_segment
    segs = [s for s in segs if len(s) >= 6]
    if not segs:
        return None
    if len(segs) == 1:
        return np.array(segs[0], np.float64).reshape(-1, 2)
    return np.concatenate(merge_multi_segment(segs), axis=0).reshape(-1, 2)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', default=f'{WS}/data/warehouse/seg_train')
    ap.add_argument('--out', default='')
    ap.add_argument('--min-area', type=int, default=40)
    ap.add_argument('--check', type=int, default=60, help='verify N val images against the GT instance masks')
    a = ap.parse_args()
    out = a.out or os.path.join(a.root, 'yolo_inst')
    names = None
    for split in ('train', 'val'):
        d = json.load(open(os.path.join(a.root, 'annotations', f'instances_{split}.json')))
        names = {c['id']: c['name'] for c in d['categories']}
        os.makedirs(os.path.join(out, 'images', split), exist_ok=True)
        os.makedirs(os.path.join(out, 'labels', split), exist_ok=True)
        by_img = {}
        for ann in d['annotations']:
            if ann['area'] >= a.min_area:
                by_img.setdefault(ann['image_id'], []).append(ann)
        n_inst = 0
        for im in d['images']:
            base = os.path.splitext(os.path.basename(im['file_name']))[0]
            dst = os.path.join(out, 'images', split, base + '.jpg')
            if not os.path.lexists(dst):
                os.symlink(os.path.relpath(os.path.join(a.root, 'images', im['file_name']), os.path.dirname(dst)), dst)
            W, H = im['width'], im['height']
            lines = []
            for ann in by_img.get(im['id'], []):
                p = merged_polygon(ann['segmentation'])
                if p is None:
                    continue
                p = p / (W, H)
                lines.append(f'{ann["category_id"] - 1} ' + ' '.join(f'{v:.5f}' for v in p.clip(0, 1).reshape(-1)))
            n_inst += len(lines)
            with open(os.path.join(out, 'labels', split, base + '.txt'), 'w') as fh:
                fh.write('\n'.join(lines) + ('\n' if lines else ''))
        print(f'{split}: {len(d["images"])} images, {n_inst} instances')
        if split == 'val' and a.check:
            check(a.root, d, by_img, a.check)
    with open(os.path.join(out, 'data.yaml'), 'w') as fh:
        fh.write('# SAVIOR-Warehouse segmentation set, instance-consistent YOLO-seg labels (one line per COCO instance,\n'
                 '# multi-polygon instances bridged). Generated by savior_datasets/warehouse/train/make_yolo_inst.py\n'
                 f'path: {out}\ntrain: images/train\nval: images/val\nnames:\n' +
                 ''.join(f'  {k - 1}: {v}\n' for k, v in sorted(names.items())))
    print(f'wrote {out}/data.yaml')


def check(root, d, by_img, n):
    """Rasterise merged polygons like ultralytics.data.utils.polygon2mask and compare with the uint16 GT ids."""
    ious = []
    for im in d['images'][:: max(1, len(d['images']) // n)][:n]:
        gt = cv2.imread(os.path.join(root, 'masks', im['file_name'].replace('.jpg', '.png')), cv2.IMREAD_UNCHANGED)
        if gt is None:
            continue
        ids, cnt = np.unique(gt, return_counts=True)
        for ann in by_img.get(im['id'], []):
            p = merged_polygon(ann['segmentation'])
            if p is None:
                continue
            m = np.zeros(gt.shape, np.uint8)
            cv2.fillPoly(m, [np.round(p).astype(np.int32)], 1)
            # the GT instance id = the id with the largest overlap inside the polygon
            vals, c = np.unique(gt[m > 0], return_counts=True)
            c, vals = c[vals > 0], vals[vals > 0]
            if not len(vals):
                continue
            g = gt == vals[np.argmax(c)]
            ious.append((g & (m > 0)).sum() / max(1, (g | (m > 0)).sum()))
    ious = np.array(ious)
    print(f'[check] {len(ious)} val instances: merged-polygon vs GT-mask IoU mean {ious.mean():.3f}, '
          f'median {np.median(ious):.3f}, <0.5: {(ious < 0.5).mean() * 100:.1f} %  '
          '(below 1: RETR_EXTERNAL fills holes, polygon simplification)')


if __name__ == '__main__':
    main()
